"""
Before/after comparison of the dashboard's numbers, run around the move onto the
registry (plan step 2: "before the Feeding page moves to the registry definition,
produce a before/after comparison of its numbers and a changelog note").

    python -m registry.dashboard_compare capture evals/results/dashboard_before.json
    ... change ui/queries.py ...
    python -m registry.dashboard_compare capture evals/results/dashboard_after.json
    python -m registry.dashboard_compare diff evals/results/dashboard_before.json \
        evals/results/dashboard_after.json > registry/CHANGELOG-dashboard.md

Guarded: only runs against the local farm_intelligence_test database (evals/guard.py).
"""

import datetime as dt
import decimal
import json
import sys

from evals.guard import connect_guarded

AUG = (dt.date(2026, 8, 1), dt.date(2026, 8, 31))
SCENARIOS = {"all time": (None, None), "Aug 2026 filter": AUG}


def _norm(x):
    if isinstance(x, decimal.Decimal):
        return round(float(x), 4)
    if isinstance(x, float):
        return round(x, 4)
    if isinstance(x, (dt.date, dt.datetime)):
        return str(x)
    if isinstance(x, dict):
        return {str(k): _norm(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_norm(v) for v in x]
    return x


def capture(path):
    from ui import queries as q
    conn = connect_guarded()
    out = {}
    for scen, (df, dt_) in SCENARIOS.items():
        kw = {"date_from": df, "date_to": dt_}
        calls = {
            "Feed cost by domain (Finance page)": lambda: q.fetch_feed_cost_by_domain(conn, **kw),
            "Feed cost by month (Feeding page)": lambda: q.fetch_feed_cost_by_month(conn, **kw),
            "Dashboard stat cards": lambda: q.fetch_dashboard_stats(conn, **kw),
            "FCR by batch (chart)": lambda: q.fetch_fcr_by_batch(conn, **kw),
            "Deaths by month (chart)": lambda: q.fetch_mortality_by_month(conn, **kw),
            "Expense breakdown (donut)": lambda: q.fetch_expense_breakdown(conn),
            "Expenses vs revenue by month": lambda: q.fetch_expenses_vs_revenue(conn, **kw),
            "Debtors": lambda: q.fetch_debtors(conn, **kw),
            "Health summary": lambda: q.fetch_health_summary(conn, **kw),
            "Breeding summary": lambda: q.fetch_breeding_summary(conn, **kw),
            "Domain lookup: piggery": lambda: q.fetch_domain_summary(conn, "piggery", **kw),
            "Domain lookup: poultry": lambda: q.fetch_domain_summary(conn, "poultry", **kw),
            "Domain lookup: crops": lambda: q.fetch_domain_summary(conn, "crops", **kw),
            "Findings": lambda: q.fetch_findings(conn, **kw),
            "Headcount by month (chart)": lambda: q.fetch_headcount_by_month(conn, **kw),
        }
        for name, fn in calls.items():
            out[f"{name} | {scen}"] = _norm(fn())
    conn.close()
    with open(path, "w") as f:
        json.dump(out, f, indent=1, sort_keys=True)
    print(f"captured {len(out)} dashboard outputs -> {path}")


def _flat(x, prefix=""):
    if isinstance(x, dict):
        for k, v in x.items():
            yield from _flat(v, f"{prefix}{k}.")
    elif isinstance(x, list):
        for i, v in enumerate(x):
            yield from _flat(v, f"{prefix}{i}.")
    else:
        yield prefix.rstrip("."), x


def _pct(b, a):
    return "-" if not b else f"{(a - b) / b * 100:+.1f}%"


def _pivot_feed_by_month(b, a):
    out = ["| month | piggery before | piggery after | change | poultry before | poultry after | change |",
           "|---|---|---|---|---|---|---|"]
    series = {dom: ({m[:7]: v for m, v in b[dom]}, {m[:7]: v for m, v in (a or {}).get(dom, [])})
              for dom in ("piggery", "poultry")}
    months = sorted(set().union(*[set(x) | set(y) for x, y in series.values()]))
    for m in months:
        cells = [m]
        for dom in ("piggery", "poultry"):
            bv, av = series[dom][0].get(m), series[dom][1].get(m)
            cells += [f"{bv:,.2f}" if bv is not None else "none", f"{av:,.2f}" if av is not None else "none",
                      _pct(bv, av) if bv is not None and av is not None else "-"]
        out.append("| " + " | ".join(cells) + " |")
    return out


def _pivot_fcr(b, a):
    bb, aa = {r["batch_code"]: r["fcr"] for r in b}, {r["batch_code"]: r["fcr"] for r in (a or [])}
    out = ["| batch | FCR before | FCR after |", "|---|---|---|"]
    for code in sorted(set(bb) | set(aa)):
        out.append(f"| {code} | {bb.get(code, 'not shown')} | {aa.get(code, 'not shown')} |")
    return out


def diff(before_path, after_path):
    b, a = json.load(open(before_path)), json.load(open(after_path))
    lines = ["## What changed, from the same fixture database before and after", "",
             "Generated by `registry/dashboard_compare.py`. Only outputs that changed are listed.", ""]
    changed = [k for k in sorted(b) if b[k] != a.get(k)]
    same = [k for k in sorted(b) if b[k] == a.get(k)]
    lines += [f"**{len(changed)} of {len(b)} dashboard outputs changed; {len(same)} are identical.**", ""]
    for k in changed:
        lines += [f"### {k}", ""]
        if k.startswith("Feed cost by month"):
            lines += _pivot_feed_by_month(b[k], a.get(k))
        elif k.startswith("FCR by batch"):
            lines += _pivot_fcr(b[k], a.get(k))
        else:
            lines += ["| field | before | after |", "|---|---|---|"]
            fb, fa = dict(_flat(b[k])), dict(_flat(a.get(k)))
            for key in sorted(set(fb) | set(fa)):
                if fb.get(key) != fa.get(key):
                    lines.append(f"| `{key}` | {fb.get(key, '-')} | {fa.get(key, '-')} |")
        lines.append("")
    lines += ["### Unchanged", ""] + [f"- {k}" for k in same]
    print("\n".join(lines))


def mortality_illustration():
    """The stat card reads 0.0% for the windows the dashboard shows by default (no deaths in them), so the
    definition change is invisible there. This shows old vs new on windows that DO have deaths."""
    from chatbot.catalog import active_headcount_asof, deaths_in_window   # the OLD definition, for comparison
    from registry import Scope, compute
    conn = connect_guarded()
    D = dt.date
    windows = [("Dec 2025", D(2025, 12, 1), D(2025, 12, 31)), ("Jan 2026", D(2026, 1, 1), D(2026, 1, 31)),
               ("Apr 2026", D(2026, 4, 1), D(2026, 4, 30)), ("May 2026", D(2026, 5, 1), D(2026, 5, 31)),
               ("Jan to Mar 2026", D(2026, 1, 1), D(2026, 3, 31)), ("All recorded time", D(2025, 10, 1), D(2026, 9, 15))]
    print("| window | deaths | old: deaths ÷ headcount at window end | new: deaths ÷ animals at risk | at risk (opening + added) |")
    print("|---|---|---|---|---|")
    for name, s, e in windows:
        start_excl = s - dt.timedelta(days=1)
        deaths = (deaths_in_window(conn, start_excl, e, "pig_daily_log") +
                  deaths_in_window(conn, start_excl, e, "poultry_daily_log"))
        base = (active_headcount_asof(conn, e, "pig_daily_log", "closing_count") +
                active_headcount_asof(conn, e, "poultry_daily_log", "closing_birds"))
        old = f"{deaths / base * 100:.2f}% (÷ {base})" if base else "0.00%"
        r = compute("mortality", conn, Scope(start=s, end=e))
        f = r.figures
        print(f"| {name} | {deaths} | {old} | {f['rate_pct']}% | {f['opening']:,} + {f['additions']:,} = {f['at_risk']:,} |")
    conn.close()


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "capture":
        capture(sys.argv[2])
    elif cmd == "diff":
        diff(sys.argv[2], sys.argv[3])
    elif cmd == "mortality":
        mortality_illustration()
    else:
        raise SystemExit("usage: capture <file> | diff <before> <after> | mortality")
