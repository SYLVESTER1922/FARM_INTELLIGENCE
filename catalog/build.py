"""
The capability catalog, generated from the registry (plan section 8). What the bot can answer is never written by hand here: it is each
metric's own `answers` / `does_not_answer` text, grouped. What it cannot answer comes from the curated list in catalog/untracked.py.

    python -m catalog.build        # rewrites catalog/CATALOG.md (a test fails if the committed file is out of date)
"""

from pathlib import Path

from catalog.untracked import KNOWN, OUT_OF_SCOPE, UNEXPOSED
from registry import REGISTRY
from render.templates import TITLES

GROUPS = (("headcount", "Animals and batches"), ("money", "Money"), ("performance", "Performance and crops"), ("operations", "Operations"))
CATALOG_PATH = Path(__file__).with_name("CATALOG.md")
_START = ("Try \"how many pigs do we have?\" or \"what was our feed cost last month?\". You can name a section "
          "(piggery, poultry, crops) and a period (\"last month\", \"March 2026\", \"year to date\").")


def metrics_by_group():
    return [(title, sorted((m for m in REGISTRY.values() if m.group == key), key=lambda m: TITLES[m.id])) for key, title in GROUPS]


def help_text() -> str:
    """The short reply to "help" / "what can I ask": the registry's metrics by group, then how to ask."""
    lines = ["I can answer questions about your farm's piggery, poultry and crops records:"]
    for title, metrics in metrics_by_group():
        lines.append(f"- {title}: " + ", ".join(TITLES[m.id].lower() for m in metrics))
    lines.append(_START)
    return "\n".join(lines)


def limits_text() -> str:
    """What the bot cannot answer, by class (for "what can't you tell me" and the catalog document)."""
    not_tracked = [u for u in KNOWN if u.kind == "not_tracked"]
    no_metric = [u for u in KNOWN if u.kind == "tracked_no_metric"]
    policy = [u for u in KNOWN if u.kind == "policy"]
    return ("Not recorded on this farm: " + "; ".join(u.hint for u in not_tracked) + ".\n"
            "Recorded, but I can't answer questions about it yet: " + "; ".join(u.hint for u in no_metric) + ".\n"
            "Not shown, by choice: " + "; ".join(u.hint for u in policy) + ".")


def catalog_markdown() -> str:
    out = ["# Chatbot capability catalog", "",
           "Generated by `python -m catalog.build` from the metric registry and `catalog/untracked.py`. Do not edit by hand.", ""]
    for title, metrics in metrics_by_group():
        out += [f"## {title}", ""]
        for m in metrics:
            out += [f"### {TITLES[m.id]} (`{m.id}`)", "", m.answers, "", f"- Not for: {m.does_not_answer}",
                    f"- Sections: {', '.join(m.domains)}",
                    f"- Period: {m.period}" + (f"; average per week" if "avg_per_week" in m.aggregations else "")
                    + (f"; month by month" if "month" in m.grains else ""),
                    f"- Breakdowns: {', '.join(m.dimensions) if m.dimensions else 'none'}",
                    f"- Zero tolerance for a wrong figure: {'yes' if m.zero_tolerance else 'no'}", ""]
    out += ["## What the bot cannot answer", ""]
    for kind, heading in (("not_tracked", "Not recorded"), ("tracked_no_metric", "Recorded, but no metric reads it yet"), ("policy", "Not shown, by choice"), ("action", "Not allowed")):
        out += [f"### {heading}", ""]
        for u in (u for u in KNOWN if u.kind == kind):
            out += [f"- **{u.code}** ({u.hint}): {u.text}"]
        out.append("")
    out += ["### Anything else", "", f"- {OUT_OF_SCOPE[1]}", "", "## Tables no metric reads", ""]
    out += [f"- `{t}` ({cls}): {why}" for t, (cls, why) in sorted(UNEXPOSED.items())]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    CATALOG_PATH.write_text(catalog_markdown())
    print(f"wrote {CATALOG_PATH}")
